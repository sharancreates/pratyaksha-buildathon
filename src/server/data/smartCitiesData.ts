function makeBoxPolygon(
  centerLng: number,
  centerLat: number,
  halfW: number,
  halfH: number,
  skew = 0.004
): [number, number][] {
  return [
    [Number((centerLng - halfW).toFixed(5)), Number((centerLat - halfH + skew).toFixed(5))],
    [Number((centerLng + halfW - skew).toFixed(5)), Number((centerLat - halfH).toFixed(5))],
    [Number((centerLng + halfW).toFixed(5)), Number((centerLat + halfH - skew).toFixed(5))],
    [Number((centerLng - halfW + skew).toFixed(5)), Number((centerLat + halfH).toFixed(5))],
    [Number((centerLng - halfW).toFixed(5)), Number((centerLat - halfH + skew).toFixed(5))],
  ];
}

function generateDeterministicHistory(
  seedOffset: number,
  baseLst: number,
  lstSlope: number,
  baseNdvi: number,
  ndviSlope: number,
  baseNo2: number,
  no2Slope: number,
  baseAqi: number,
  baseWater: number,
  waterSlope: number
): DailyObservationPoint[] {
  const points: DailyObservationPoint[] = [];
  // Fixed deterministic anchor date for reproducible hackathon demo
  const endDate = new Date('2026-11-19T00:00:00Z');
  for (let i = 89; i >= 0; i--) {
    const d = new Date(endDate.getTime() - i * 86400000);
    const dayIdx = 89 - i;
    const seasonal = Math.sin(((dayIdx + seedOffset) / 14) * Math.PI);
    const weekly = Math.cos(((dayIdx + seedOffset * 2) / 7) * Math.PI);
    const micro = Math.sin((dayIdx * 3.7 + seedOffset) * 0.85);

    const lst = Number((baseLst + lstSlope * (dayIdx / 89) + seasonal * 1.45 + micro * 0.55).toFixed(2));
    const ndvi = Number(
      Math.max(0.08, Math.min(0.78, baseNdvi + ndviSlope * (dayIdx / 89) - seasonal * 0.025 + micro * 0.012)).toFixed(3)
    );
    const no2 = Number(
      Math.max(12, baseNo2 + no2Slope * (dayIdx / 89) + weekly * 8.4 + micro * 4.2).toFixed(1)
    );
    const aqi = Math.round(
      Math.max(35, baseAqi + no2Slope * 0.65 * (dayIdx / 89) + weekly * 16 + micro * 8)
    );
    const waterExtentKm2 = Number(
      Math.max(1.2, baseWater + waterSlope * (dayIdx / 89) + Math.sin(dayIdx / 20) * 0.35).toFixed(2)
    );
    const cloudCoverPct = Number(
      Math.max(2, Math.min(48, 12 + Math.abs(Math.sin(dayIdx * 0.43 + seedOffset)) * 22)).toFixed(1)
    );

    points.push({
      date: d.toISOString().slice(0, 10),
      lst,
      ndvi,
      no2,
      aqi,
      waterExtentKm2,
      cloudCoverPct,
    });
  }
  return points;
}

